"""Generate the aotpport symbol headers from port/symbols.csv (INTRO.EXE, PS.EXE, AP_flat.exe).

Per program (exe column intro / ps / ap), aotpport/src/symbols_<exe>.h:
  DGROUP globals          #define <EXE>_DS_<name>  0xXXXX          (DSB/DSW/DSS/DSL from mem.h, used
                                                                    while that program is current)
  code-segment globals    #define <EXE>_CS_<name>  0xXXXX          (offset in its segment)
                          #define <EXE>_CSSEG_<name> 0xSSSS        (file segment: SEGB/SEGW)
  functions               #define <EXE>_FN_<name>  0xSSSSOOOOu     (file segment << 16 | offset; AP =
                                                                    work/AP_flat.exe addresses)
  Duplicate names inside one program get an address suffix. Owner and type are kept as a comment.

Shared library layout (platform.md 9.1, option 1), aotpport/src/symbols_layout.h / .c:
  every DGROUP global whose name exists in at least two programs gets an id G_<name>; every function
  name that exists (once) in at least two programs gets an id F_<name>. ProgLayout tables
  layout_intro / layout_ps / layout_ap hold its DS offset (LAYOUT_ABSENT_DS if the program has no
  such global) and its code address (LAYOUT_ABSENT_FN).

usage: python tools/gen_symbols.py      (from the repository root, after tools/merge_symbols.py)
"""
import csv, os, re
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXES = ('intro', 'ps', 'ap')
rows = list(csv.DictReader(open(os.path.join(ROOT, 'port', 'symbols.csv'), encoding='utf-8')))
DST = os.path.join(ROOT, 'aotpport', 'src')


def ident(name):
    name = re.sub(r'\W', '_', name)
    return ('_' + name) if name[:1].isdigit() else name


def key(r):
    a = r['address']
    if a.startswith('DS:'):
        return (0, 0, int(a[3:], 16))
    s, o = a.split(':')
    return (1, int(s, 16), int(o, 16))


def comment(r):
    typ = r['type'].replace('*/', '* /').replace('/*', '/ *').replace('\n', ' ')[:48]
    typ = typ.rstrip('/').rstrip('*')                # a cut may leave "/" or "*" before the "*/"
    return '/* %s%s */' % (r['owner'], (', ' + typ) if typ else '')


def write(name, lines):
    path = os.path.join(DST, name)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(lines) + '\n')
    return path


summary = []
for exe in EXES:
    mine = [r for r in rows if r['exe'] == exe]
    P = exe.upper()
    out = ['/* Generated by tools/gen_symbols.py from port/symbols.csv (%s). Do not edit. */' % P,
           '#pragma once', '']
    ds = sorted((r for r in mine if r['kind'] == 'global' and r['address'].startswith('DS:')), key=key)
    cs = sorted((r for r in mine if r['kind'] == 'global' and not r['address'].startswith('DS:')), key=key)
    fn = sorted((r for r in mine if r['kind'] == 'func'), key=key)
    for title, sel, kind in (('DGROUP globals (offsets for DSB/DSW/DSS/DSL)', ds, 'DS'),
                             ('Code-segment globals (CS_x offset, CSSEG_x file segment)', cs, 'CS'),
                             ('Original functions (file segment << 16 | offset)', fn, 'FN')):
        counts = Counter(ident(r['name']) for r in sel)
        out.append('/* ---- %s */' % title)
        for r in sel:
            n = ident(r['name'])
            k = key(r)
            if counts[n] > 1:
                n = '%s_%04X' % (n, k[2]) if k[0] == 0 else '%s_%04X_%04X' % (n, k[1], k[2])
            if kind == 'DS':
                out.append('#define %-48s 0x%04X  %s' % ('%s_DS_%s' % (P, n), k[2], comment(r)))
            elif kind == 'CS':
                out.append('#define %-48s 0x%04X  %s' % ('%s_CS_%s' % (P, n), k[2], comment(r)))
                out.append('#define %-48s 0x%04X' % ('%s_CSSEG_%s' % (P, n), k[1]))
            else:
                out.append('#define %-48s 0x%04X%04Xu  %s' % ('%s_FN_%s' % (P, n), k[1], k[2], comment(r)))
        out.append('')
    write('symbols_%s.h' % exe, out)
    summary.append('%s: %d DGROUP globals, %d code-segment globals, %d functions'
                   % (P, len(ds), len(cs), len(fn)))

# ---- shared library layout ----
g = defaultdict(dict)          # name -> exe -> DS offset
f = defaultdict(lambda: defaultdict(list))
for r in rows:
    if r['kind'] == 'global' and r['address'].startswith('DS:'):
        g[ident(r['name'])].setdefault(r['exe'], []).append(key(r)[2])
    elif r['kind'] == 'func':
        k = key(r)
        f[ident(r['name'])][r['exe']].append(k[1] << 16 | k[2])
gnames = sorted(n for n in g if len(g[n]) >= 2 and all(len(v) == 1 for v in g[n].values()))
fnames = sorted(n for n in f if len(f[n]) >= 2 and all(len(v) == 1 for v in f[n].values()))

h = ['/* Generated by tools/gen_symbols.py from port/symbols.csv. Do not edit.',
     ' *',
     ' * Shared-library layout (platform.md 9.1, option 1; aotpport/PORTING.md "Shared library"):',
     ' * the Dynamix system library and the Borland RTL are the same code in INTRO, PS and AP, but their',
     ' * globals sit at different DS offsets and their functions at different addresses. Library code',
     ' * is written once and addresses its globals through the current program\'s layout:',
     ' *     LW(G_timer_countdown) -= 1;         (mem.h: DSW(prog_layout->ds[G_timer_countdown]))',
     ' * A global/function a program does not have is LAYOUT_ABSENT_DS / LAYOUT_ABSENT_FN. */',
     '#pragma once',
     '#include "types.h"', '',
     '#define LAYOUT_ABSENT_DS 0xFFFFu',
     '#define LAYOUT_ABSENT_FN 0xFFFFFFFFu', '',
     '/* ---- DGROUP globals present in at least two programs */',
     'enum {']
for n in gnames:
    h.append('    G_%s,' % n)
h += ['    G_COUNT', '};', '', '/* ---- Functions present in at least two programs */', 'enum {']
for n in fnames:
    h.append('    F_%s,' % n)
h += ['    F_COUNT', '};', '',
      'typedef struct {',
      '    const char *exe;            /* "intro", "ps", "ap" */',
      '    u16 ds[G_COUNT];            /* DS offset of each shared global */',
      '    u32 fn[F_COUNT];            /* file segment << 16 | offset of each shared function */',
      '} ProgLayout;', '',
      'extern const ProgLayout layout_intro, layout_ps, layout_ap;',
      'extern const char *const layout_g_names[G_COUNT];',
      'extern const char *const layout_f_names[F_COUNT];']
write('symbols_layout.h', h)

c = ['/* Generated by tools/gen_symbols.py from port/symbols.csv. Do not edit. */',
     '#include "symbols_layout.h"', '']
for exe in EXES:
    c.append('const ProgLayout layout_%s = {' % exe)
    c.append('    "%s",' % exe)
    c.append('    {')
    for n in gnames:
        v = g[n].get(exe)
        c.append('        %s, /* %s */' % (('0x%04X' % v[0]) if v else 'LAYOUT_ABSENT_DS', n))
    c.append('    },')
    c.append('    {')
    for n in fnames:
        v = f[n].get(exe)
        c.append('        %s, /* %s */' % (('0x%08Xu' % v[0]) if v else 'LAYOUT_ABSENT_FN', n))
    c.append('    },')
    c.append('};')
    c.append('')
c.append('const char *const layout_g_names[G_COUNT] = {')
c += ['    "%s",' % n for n in gnames]
c.append('};')
c.append('const char *const layout_f_names[F_COUNT] = {')
c += ['    "%s",' % n for n in fnames]
c.append('};')
write('symbols_layout.c', c)

for s in summary:
    print(s)
print('layout: %d shared DGROUP globals, %d shared functions -> %s' % (len(gnames), len(fnames), DST))
